public class while_1 {
    public static void main(String[] args){
        System.out.println("\n1. contar de 1 ate 5 com while\n");
        int contador = 1;
        while (contador <=5){
            System.out.println("Contador: " + contador);
            contador++;
        }
        int numero = 5;
        while (numero >= 1 ){
            System.out.println("Numero: " + numero);
            numero--;
        }
    }
}
